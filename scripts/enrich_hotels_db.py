    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--refresh", action="store_true", help="overwrite existing descriptions with regenerated text")
    parser.add_argument("--sql", type=Path, default=None, help="also write the updates as a SQL file")
    args = parser.parse_args()
    asyncio.run(main(args.refresh, args.sql))
