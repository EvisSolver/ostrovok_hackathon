# 3. ЗАПРОС ПОЛЬЗОВАТЕЛЯ
# Обратите внимание, что слов "звукоизоляция" или "спикизи" в запросе нет!
user_query = "ищу дорогой вариант с барами и тусовками"
print(f"Запрос пользователя: '{user_query}'\n")

# === МАТЕМАТИКА ВЕКТОРНОГО ПОИСКА ===

# Шаг А: Превращаем все описания отелей в векторы смыслов (это происходит локально)
hotel_descriptions = [hotel["desc"] for hotel in hotels_db]
hotel_vectors = model.encode(hotel_descriptions)

# Шаг Б: Превращаем запрос пользователя в такой же вектор
query_vector = model.encode(user_query)


# Шаг В: Функция расчета косинусного сходства (угол между векторами в пространстве смыслов)
def get_similarity(v1, v2):
    return np.dot(v1, v2) / (np.linalg.norm(v1) * np.linalg.norm(v2))


# Шаг Г: Считаем схожесть запроса с каждым отелем в базе
results = []
for idx, hotel_vec in enumerate(hotel_vectors):
    score = get_similarity(query_vector, hotel_vec)
    results.append({"hotel": hotels_db[idx], "score": score})

# Шаг Д: Сортируем результаты по убыванию балла (от самых подходящих к наименее подходящим)
results = sorted(results, key=lambda x: x["score"], reverse=True)

# 4. ВЫВОД ТОП-3 ЛУЧШИХ ОТЕЛЕЙ
print("=== ТОП-3 САМЫХ ПОДХОДЯЩИХ ОТЕЛЕЙ ===")
for i in range(3):
    match = results[i]
    hotel = match["hotel"]
    # Переводим оценку в понятные проценты совпадения
    percentage = round(float(match["score"]) * 100, 1)

    print(f"{i+1}. {hotel['name']} (Совпадение смыслов: {percentage}%)")
    print(f"   Описание: {hotel['desc']}\n")
